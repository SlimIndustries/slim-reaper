'use strict';
// The bridge between the UI and the main process. The UI can only call these functions.
const { contextBridge, ipcRenderer, webUtils } = require('electron');

const call = (ch) => (...args) => ipcRenderer.invoke(ch, ...args);

contextBridge.exposeInMainWorld('reaper', {
  getState: call('get-state'),
  saveSettings: call('save-settings'),
  pickFolder: call('pick-folder'),
  makeFolder: call('make-folder'),
  importUrls: call('import-urls'),
  readDroppedFile: call('read-dropped-file'),
  extractUrls: call('extract-urls'),
  startScan: call('start-scan'),
  addToScan: call('add-to-scan'),
  pause: call('pause'),
  resume: call('resume'),
  stop: call('stop'),
  skipJob: call('skip-job'),
  openPath: call('open-path'),
  showInFolder: call('show-in-folder'),
  openExternal: call('open-external'),
  copyText: call('copy-text'),
  copyImage: call('copy-image'),
  setWallpaper: call('set-wallpaper'),
  fileExists: call('file-exists'),
  imageInfo: call('image-info'),
  getSessionImages: call('get-session-images'),
  getHistory: call('get-history'),
  deleteSession: call('delete-session'),
  clearHistory: call('clear-history'),
  exportReport: call('export-report'),
  exportLog: call('export-log'),
  exportSettings: call('export-settings'),
  importSettings: call('import-settings'),
  forgetMemory: call('forget-memory'),
  trashFiles: call('trash-files'),
  removeFromApp: call('remove-from-app'),
  copyFiles: call('copy-files'),
  startDrag: (paths) => ipcRenderer.send('start-drag', paths),
  previewUrl: call('preview-url'),
  pickAnyFolder: call('pick-any-folder'),
  dupesScan: call('dupes-scan'),
  dupesCancel: call('dupes-cancel'),
  saveReport: call('save-report'),
  sessionFolders: call('session-folders'),
  renameFolder: call('rename-folder'),
  onPathsRenamed: (fn) => ipcRenderer.on('paths-renamed', (e, x) => fn(x)),
  onFilesRemoved: (fn) => ipcRenderer.on('files-removed', (e, paths) => fn(paths)),
  onDupesProgress: (fn) => ipcRenderer.on('dupes-progress', (e, p) => fn(p)),
  listSignIns: call('list-signins'),
  signIn: call('sign-in'),
  signOut: call('sign-out'),
  runSchedulesNow: call('run-schedules-now'),
  pathForFile: (file) => { try { return webUtils.getPathForFile(file); } catch { return ''; } },
  onEvents: (fn) => ipcRenderer.on('engine-events', (e, batch) => fn(batch)),
  onClipboardUrls: (fn) => ipcRenderer.on('clipboard-urls', (e, urls) => fn(urls)),
  onSignInsChanged: (fn) => ipcRenderer.on('signins-changed', () => fn()),
  onScheduleStarted: (fn) => ipcRenderer.on('schedule-started', (e, info) => fn(info))
});
